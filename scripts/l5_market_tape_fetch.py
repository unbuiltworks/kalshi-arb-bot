"""Fetch the MARKET-WIDE print tape for L5's BTC15m windows. Read-only.

Why this exists
---------------
Every earlier side model in this repository derived the market price from
L5'S OWN FILL PRICES (`next_side/features.py`: `p_up = px if side == "Up"
else 1 - px`). That is endogenous: the "favorite" it reports is a function of
the side L5 chose, so "L5 buys the favorite" would be partly true by
construction. A FAVORITE/FLIP test needs a price series generated by someone
other than L5.

This fetches `data-api.polymarket.com/trades?market=<conditionId>`, which
returns every print in the market with its `proxyWallet`, so L5's own prints
can be DROPPED and the favorite rebuilt from counterparty flow alone. Both
series are kept: `p_up_ex` (exogenous) and `p_up_all`, so the endogeneity can
be measured rather than asserted.

Prints only. There is no book here: no bid, no ask, no depth. A favorite
derived from prints is a last-traded favorite, and that limit is carried into
the output rather than papered over.
"""
from __future__ import annotations
import argparse, gzip, json, os, sys, time
import urllib.request, urllib.error

API = "https://data-api.polymarket.com/trades"
OUT = "data/l5/market_tape"
PAGE = 500
L5 = None  # filled from --l5-wallet


def _get(url: str, tries: int = 5):
    last = None
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "l5-research"})
            with urllib.request.urlopen(req, timeout=45) as r:
                return json.loads(r.read().decode())
        except Exception as e:                                  # noqa: BLE001
            last = e
            time.sleep(min(2 ** i, 16))
    raise RuntimeError("GET failed after %d tries: %s (%s)" % (tries, url, last))


def fetch_window(cid: str) -> list:
    """Every print in the market, paginated to exhaustion.

    Pagination is validated, not trusted: a page that repeats the previous
    page's transaction hashes stops the loop, so a server that ignores
    `offset` cannot silently produce a duplicated tape.
    """
    out, seen, off = [], set(), 0
    while True:
        rows = _get("%s?market=%s&limit=%d&offset=%d" % (API, cid, PAGE, off))
        if not rows:
            break
        fresh = [r for r in rows
                 if (r.get("transactionHash"), r.get("asset"), r.get("size"),
                     r.get("timestamp")) not in seen]
        for r in rows:
            seen.add((r.get("transactionHash"), r.get("asset"), r.get("size"),
                      r.get("timestamp")))
        if not fresh:
            break
        out.extend(fresh)
        if len(rows) < PAGE:
            break
        off += PAGE
    return out


KEEP = ("proxyWallet", "side", "asset", "size", "price", "timestamp",
        "outcome", "outcomeIndex", "transactionHash", "slug")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--windows", required=True)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    ws = json.load(open(a.windows))
    if a.limit:
        ws = ws[:a.limit]
    os.makedirs(a.out, exist_ok=True)
    done = n_new = 0
    for w in ws:
        p = os.path.join(a.out, "%s.jsonl.gz" % w["slug"])
        if os.path.exists(p):
            done += 1
            continue
        rows = fetch_window(w["window_id"])
        tmp = p + ".part"
        with gzip.open(tmp, "wt") as f:
            f.write(json.dumps({"kind": "provenance", "source": API,
                                "window_id": w["window_id"],
                                "slug": w["slug"], "rows": len(rows),
                                "fetched_utc": time.strftime(
                                    "%Y-%m-%dT%H:%M:%SZ", time.gmtime())}) + "\n")
            for r in rows:
                f.write(json.dumps({k: r.get(k) for k in KEEP}) + "\n")
        os.replace(tmp, p)
        n_new += 1
        print("%s %d rows" % (w["slug"], len(rows)), flush=True)
    print("already_present=%d fetched=%d" % (done, n_new))
    return 0


if __name__ == "__main__":
    sys.exit(main())
