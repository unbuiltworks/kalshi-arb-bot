#!/usr/bin/env python3
"""The corrected arm and the control, SEGMENTED BY TTE BAND.

WHY BANDS AND NOT TOTALS. The control cannot act above tte 300 at all, so a
totals-only comparison hands the corrected arm every fill above 300 and says
nothing about whether the two behave differently where BOTH can act. Reading
>600 / 300-600 / <=300 separately keeps those three questions apart:

  >600        the interval the correction exists to reach, and where L5 takes
              89.5% of his OPENs. The control is structurally absent here.
  300-600     also new, and where L5's recycling is strongest (recycle 1.003,
              median basis 0.952).
  <=300       THE OVERLAP. Both arms can act. If they diverge here, something
              other than timing moved, and the one-field claim is false.

METHODOLOGY IS THE L5 SEGMENTATION'S, DELIBERATELY. Pair economics are
attributed to the band of the COMPLETE fill, residual is generated by
OPEN/EXTEND and recycled by COMPLETE, and matched-gross is matched notional
over gross notional -- the same definitions `analysis/l5/tte/segments.py`
uses on L5's own fills, so the two venues' tables can be read side by side.

A FILL HERE IS THE SYSTEM'S OWN SHADOW FILL. Rows come from
`hypothetical.HypotheticalBook.consume`, which walks prints against resting
rungs with `tape_replay.reaches`. A print that merely crosses a price we
never rested is NOT a fill and never becomes one here. Queue position is
UNOBSERVABLE -- Gemini serves no book history -- so every row is an upper
bound conditional on having been reached.
"""
from __future__ import annotations

from decimal import Decimal as D
from decimal import InvalidOperation
from typing import Any, Dict, List, Mapping, Optional, Sequence

#: Gemini's published maker rate; one leg's fee is rate * qty * p * (1 - p)
MAKER_RATE = D("0.0175")

#: the three questions, in the order they are asked
BANDS = ((">600", 600.0, float("inf")),
         ("300-600", 300.0, 600.0),
         ("<=300", 0.0, 300.0))

CONTROL = "CONTROL"

LABELS = (
    "HYPOTHETICAL. No order existed and nothing was submitted, filled, "
    "settled or realized; no figure here is a cost basis or realized "
    "profit. Fills are the system's own shadow fills (tape_replay.reaches "
    "against rungs that were resting), never bare tape crossings. Queue "
    "position is UNOBSERVABLE, so every count is an upper bound.")


def _dec(v: Any) -> Optional[D]:
    try:
        return D(str(v))
    except (InvalidOperation, TypeError, ValueError):
        return None


def band_of(tte_s: Any) -> Optional[str]:
    t = _dec(tte_s)
    if t is None:
        return None
    t = float(t)
    for name, lo, hi in BANDS:
        if lo <= t < hi:
            return name
    return None


def maker_fee(qty: D, price: D) -> D:
    return MAKER_RATE * qty * price * (D("1") - price)


def _blank() -> Dict[str, Any]:
    return {"readable_cycles": 0, "unreadable_cycles": 0,
            "rungs_rested": 0, "fills": 0, "first_fills": 0,
            "open_fills": 0, "extend_fills": 0, "complete_fills": 0,
            "matched_pairs": 0, "fee_positive_pairs": 0,
            "matched_qty": D("0"), "gross_qty": D("0"),
            "residual_generated": D("0"), "residual_recycled": D("0"),
            "fills_on_an_unknown_queue": 0, "_bases": []}


def _walk_window(fills: Sequence[Mapping[str, Any]],
                 acc: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """One window's fills, in order, with pair economics per band.

    Inventory is carried sequentially exactly as the live arm carried it: a
    COMPLETE is priced against the average cost of the leg it is closing, so
    the basis is the pair's, not a single leg's.
    """
    held: Dict[str, D] = {"YES": D("0"), "NO": D("0")}
    spend: Dict[str, D] = {"YES": D("0"), "NO": D("0")}
    terminal_leg = None
    for f in fills:
        leg = str(f.get("leg") or "")
        qty = _dec(f.get("qty"))
        px = _dec(f.get("price"))
        b = band_of(f.get("tte_s"))
        if leg not in held or qty is None or px is None or b is None:
            continue
        a = acc[b]
        a["fills"] += 1
        a["gross_qty"] += qty
        if f.get("was_first_fill"):
            a["first_fills"] += 1
        if not f.get("queue_known"):
            a["fills_on_an_unknown_queue"] += 1

        kind = str(f.get("kind") or "")
        other = "NO" if leg == "YES" else "YES"
        # a COMPLETE is a fill on the leg OPPOSITE the one we are holding
        completing = held[other] > 0
        if kind == "COMPLETE" or (not kind and completing):
            a["complete_fills"] += 1
        elif kind == "OPEN":
            a["open_fills"] += 1
        elif kind == "EXTEND":
            a["extend_fills"] += 1

        if completing:
            m = min(qty, held[other])
            if m > 0:
                avg = spend[other] / held[other]
                basis = avg + px
                a["matched_pairs"] += 1
                a["matched_qty"] += m
                fees = maker_fee(m, avg) + maker_fee(m, px)
                per_pair_fee = fees / m
                if basis + per_pair_fee <= D("1"):
                    a["fee_positive_pairs"] += 1
                if D("0") < basis <= D("2"):
                    a["_bases"].append(basis)
                a["residual_recycled"] += m
                spend[other] -= avg * m
                held[other] -= m
                qty -= m
        if qty > 0:
            held[leg] += qty
            spend[leg] += qty * px
            a["residual_generated"] += qty
            terminal_leg = leg

    residual = held["YES"] - held["NO"]
    return {"terminal_residual": str(residual),
            "terminal_leg": (terminal_leg if residual != 0 else None)}


def bands(windows: Sequence[Mapping[str, Any]], label: str) -> Dict[str, Any]:
    """One arm's banded table over completed windows."""
    acc = {name: _blank() for name, _, _ in BANDS}
    terminal: List[Dict[str, Any]] = []
    n_windows = 0

    for w in windows:
        if label == CONTROL:
            hyp = w.get("hypothetical") or {}
            cycles = w.get("cycles_detail") or []
            def cyc_arm(c):
                return c
        else:
            arms = w.get("correction_arms") or {}
            if label not in arms:
                continue                       # window predates this arm
            hyp = (arms[label] or {}).get("hypothetical") or {}
            cycles = w.get("cycles_detail") or []
            def cyc_arm(c, _l=label):
                return ((c.get("correction_arms") or {}).get(_l) or {})
        n_windows += 1

        # ---- readability and rungs, per cycle, banded by the cycle's TTE
        last_cum: Dict[str, int] = {}
        for c in sorted(cycles, key=lambda r: r.get("cycle") or 0):
            b = band_of(c.get("tte_s"))
            if b is None:
                continue
            hab = c.get("habitat") or {}
            if hab.get("book_readable"):
                acc[b]["readable_cycles"] += 1
            else:
                acc[b]["unreadable_cycles"] += 1
            rec = cyc_arm(c)
            cum = rec.get("hypothetical_rungs_rested_cumulative")
            if cum is None:
                continue
            prev = last_cum.get("v", 0)
            delta = int(cum) - prev
            if delta > 0:
                acc[b]["rungs_rested"] += delta
            last_cum["v"] = int(cum)

        terminal.append(dict(_walk_window(hyp.get("rows") or [], acc),
                             symbol=w.get("symbol")))

    out: Dict[str, Any] = {}
    for name, a in acc.items():
        bs = sorted(a.pop("_bases"))
        n = len(bs)
        med = (None if not n else
               (bs[n // 2] if n % 2 else (bs[n // 2 - 1] + bs[n // 2])
                / D("2")))
        gross = a["gross_qty"]
        out[name] = dict(
            a,
            matched_qty=str(a["matched_qty"]),
            gross_qty=str(gross),
            residual_generated=str(a["residual_generated"]),
            residual_recycled=str(a["residual_recycled"]),
            actual_pair_basis_median=(None if med is None else str(med)),
            matched_gross=(None if gross == 0 else
                           str((a["matched_qty"] / gross)
                               .quantize(D("0.0001")))),
        )
    return {"arm": label, "windows": n_windows, "bands": out,
            "terminal_residual_by_window": terminal, "labels": LABELS}
