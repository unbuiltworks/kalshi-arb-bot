"""Ed25519-signed owner mandates. Verification only -- nothing here arms.

WHY A SIGNATURE RATHER THAN A HIDING PLACE. `l5_campaign_approval` reads the
approval from a Railway variable and its docstring claims "Claude cannot write
it, so Claude cannot approve a campaign". That is false in practice: anyone
holding a Railway token can set the variable, and in session 012Mo8AP three
were set that way. Moving the document to another store only moves the same
problem, because the executor's operator can reach every store the executor
can. So this module does not try to control CUSTODY of the bytes. It makes
writing the bytes INSUFFICIENT: the payload must carry an Ed25519 signature
from a key whose public half is compiled in here and whose private half the
owner holds offline. An attacker -- or a well-meaning agent -- who can write
the variable still cannot produce a document that verifies.

WHAT IS SIGNED IS WHAT IS ENFORCED. The signature covers a canonical
serialization of the whole payload: venue, strategy, environment, service
role, series, validity window, allowed actions, execution mode, per-day
action rates, capital envelope, loss limits, residual cap and the promotion
preconditions. A field outside that payload cannot influence authorization,
and an UNKNOWN field inside it is a REFUSAL rather than something ignored --
because a typo in an owner-signed document that silently grants different
scope than the owner read back is the failure this schema exists to prevent.

FAIL CLOSED, ALWAYS. Absent, malformed, unknown key, bad signature, naive
timestamp, not yet valid, expired, over the duration ceiling, rolled back,
revoked, or unreadable high-water mark all return `ok: False` with a named
reason. There is exactly one path to True.

THIS MODULE IS PURE WITH RESPECT TO MONEY. It places nothing, cancels
nothing, prices nothing and arms nothing. In phase 1 it is wired only to
`l5_runtime_config_verify`, which reports.

THE PRIVATE KEY NEVER EXISTS HERE. Not in this repository, not in Railway,
not in any environment the executor can read, and it is never generated by an
agent. `docs/OWNER_MANDATE_SIGNING.md` is the owner's offline procedure.
"""
from __future__ import annotations

import datetime as dt
import json
import os
from decimal import Decimal as D, InvalidOperation
from typing import Any, Dict, Mapping, Optional, Tuple

#: THE TRUSTED PUBLIC KEYS, as {key_id: hex-encoded 32-byte Ed25519 public
#: key}. EMPTY IS THE SHIPPED STATE and it means no mandate can verify, which
#: is the correct default: an empty registry refuses everything rather than
#: trusting anything. The owner generates the pair offline (see the signing
#: doc) and the PUBLIC half is committed here in a reviewed change.
#:
#: A key is retired by DELETING its entry. Never reuse a key_id for a
#: different key: `seq` monotonicity is tracked per key_id, so reusing an id
#: would let an old sequence number apply to a new key.
MANDATE_PUBKEYS: Dict[str, str] = {
    # "owner-2026-10": "<64 hex chars>",
}

#: the schema this code understands. A document naming anything else is
#: refused rather than best-effort parsed.
SCHEMA = "l5.mandate.v1"

#: the longest a single signed mandate may be valid for, regardless of what
#: it asks for. 30 days replaces the 4-hour campaign clamp; it is still a
#: bound, so a forgotten mandate expires rather than running for ever.
MAX_MANDATE_S = 30 * 24 * 3600.0

#: what this executor is. A mandate must name all of these exactly, so a
#: document signed for the sports strategy, a staging environment or another
#: service role cannot authorize this one.
EXPECTED_VENUE = "PMUS"
EXPECTED_STRATEGY = "l5-two-sided-btc15m"
EXPECTED_EXECUTION_MODE = "MAKER_ONLY"

#: actions a mandate may name. A document naming anything outside this set is
#: refused -- the set is the code's, not the document's.
KNOWN_ACTIONS = ("OPEN", "COMPLETE", "REPLACE", "CANCEL")

#: TAKER CROSSING IS NOT EXPRESSIBLE. There is deliberately no action name
#: for it and `execution_mode` must equal MAKER_ONLY, so no signed mandate
#: can authorize a crossing order. Defensive crossing stays governed by
#: L5_DEFENSIVE_COMPLETION, which the runtime verifier grades separately.

REQUIRED_PAYLOAD_FIELDS = (
    "schema", "kind", "mandate_id", "seq", "venue", "strategy",
    "environment", "service_role", "series", "not_before", "not_after",
    "allowed_actions", "execution_mode", "max_windows_per_day",
    "max_submissions_per_day", "capital", "loss_limits",
    "residual_cap_contracts", "promotion",
)
REQUIRED_CAPITAL_FIELDS = ("max_cash_deployed_usd", "max_total_exposure_usd",
                           "campaign_budget_usd")
REQUIRED_LOSS_FIELDS = ("daily_realized_loss_halt_usd",
                        "max_cumulative_loss_usd")
#: PROMOTION IS A BLOCK, NEVER A SWITCH. `requires_bounded_live_validation`
#: must be true: a mandate that sets it false is REFUSED, so there is no way
#: to express "go live as soon as shadow expectancy turns positive". Shadow
#: evidence can only ever WITHHOLD live arming; enabling it additionally
#: requires the named out-of-sample evidence and a separate bounded live
#: validation recorded against that id.
REQUIRED_PROMOTION_FIELDS = ("min_settled_windows", "min_expectancy_usd",
                             "oos_evidence_id",
                             "requires_bounded_live_validation")

#: where the replay/rollback high-water mark lives.
SEQ_DIR = "mandate_seq"
SEQ_ROOT_ENV = "L5_LIVE_ROOT"
#: the owner-set document, read by the existing EnvApprovalStore medium.
MANDATE_ENV = "L5_MANDATE_DOC"


class MandateUnavailable(RuntimeError):
    """The answer could not be established. NOT the same as 'no mandate'."""


def _utc() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


def _ts(v: Any) -> Optional[dt.datetime]:
    """ISO-8601 with an explicit offset, or None. A NAIVE TIMESTAMP IS NONE:
    'midnight' without a zone is a different instant in every zone, and
    guessing UTC on the owner's behalf is how a mandate becomes valid hours
    before they intended."""
    try:
        t = dt.datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None
    return t if t.tzinfo is not None else None


def _money(v: Any) -> Optional[D]:
    """A finite non-negative Decimal from a STRING. Floats are refused: 0.1
    is not 0.1 in binary and a limit that differs from the one the owner
    signed is not the owner's limit."""
    if isinstance(v, float) or isinstance(v, bool):
        return None
    try:
        d = D(str(v))
    except (InvalidOperation, ValueError, TypeError, ArithmeticError):
        return None
    return d if (d.is_finite() and d >= 0) else None


def _pos_int(v: Any) -> Optional[int]:
    if isinstance(v, bool) or not isinstance(v, int):
        return None
    return v if v >= 1 else None


def canonical_bytes(payload: Mapping[str, Any]) -> bytes:
    """The exact bytes the owner signs.

    Sorted keys, no whitespace, ASCII-escaped: one payload has one encoding,
    so a signature cannot be invalidated by re-serialization and two
    different payloads cannot share a signature.
    """
    return json.dumps(payload, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True).encode("utf-8")


def _verify_ed25519(pub_hex: str, sig_hex: str, msg: bytes) -> bool:
    """True only on a cryptographically valid signature.

    Uses `cryptography`, already a dependency (>=42.0) and already the Ed25519
    implementation behind `pmus_auth`, so this adds no package. Every failure
    -- bad hex, wrong length, invalid signature, missing backend -- is False.
    """
    try:
        from cryptography.hazmat.primitives.asymmetric import ed25519
        from cryptography.exceptions import InvalidSignature
    except BaseException:                                      # noqa: BLE001
        return False
    try:
        pub = bytes.fromhex(str(pub_hex).strip())
        sig = bytes.fromhex(str(sig_hex).strip())
    except (ValueError, TypeError, AttributeError):
        return False
    if len(pub) != 32 or len(sig) != 64:
        return False
    try:
        ed25519.Ed25519PublicKey.from_public_bytes(pub).verify(sig, msg)
        return True
    except InvalidSignature:
        return False
    except BaseException:                                      # noqa: BLE001
        return False


class SeqStore:
    """Per-key_id monotonic high-water mark: replay and rollback protection.

    A mandate whose `seq` is not STRICTLY GREATER than the highest seq ever
    accepted for its key_id is refused. That stops both replaying a captured
    document and rolling back to a genuinely-signed older one whose limits
    were looser.

    AN UNREADABLE MARK RAISES. Reporting it as zero would make a corrupt file
    indistinguishable from a fresh install and accept any seq at all.

    KNOWN PHASE-1 LIMITATION, stated rather than papered over: this file sits
    on the EXECUTOR's volume, so the executor could in principle delete it
    and replay an old mandate. Before enforcement, the mark must move to the
    watchdog-owned store that already holds the halt latch, where the
    executor's only verb is GET. Until then rollback protection is ADVISORY.
    """

    def __init__(self, root: Optional[str] = None) -> None:
        base = root or os.getenv(SEQ_ROOT_ENV, "").strip() or "."
        self.dir = os.path.join(base, SEQ_DIR)

    def _path(self, key_id: str) -> str:
        safe = "".join(c for c in str(key_id) if c.isalnum() or c in ".-_")
        if not safe:
            raise ValueError("empty key id")
        return os.path.join(self.dir, "%s.json" % safe)

    def highest(self, key_id: str) -> int:
        try:
            with open(self._path(key_id), "r") as fh:
                doc = json.load(fh)
        except FileNotFoundError:
            return 0
        except BaseException as exc:                           # noqa: BLE001
            if isinstance(exc, (KeyboardInterrupt, SystemExit)):
                raise
            raise MandateUnavailable(
                "seq store unreadable: %s" % type(exc).__name__) from exc
        v = doc.get("highest_seq") if isinstance(doc, dict) else None
        if not isinstance(v, int) or isinstance(v, bool) or v < 0:
            raise MandateUnavailable("seq store malformed")
        return v

    def record(self, key_id: str, seq: int) -> None:
        """Raise the mark. NEVER LOWERS IT, so a replayed document cannot
        reopen the window it just closed."""
        cur = self.highest(key_id)
        if int(seq) <= cur:
            return
        os.makedirs(self.dir, exist_ok=True)
        tmp = self._path(key_id) + ".tmp"
        with open(tmp, "w") as fh:
            json.dump({"key_id": str(key_id), "highest_seq": int(seq)}, fh,
                      sort_keys=True)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, self._path(key_id))


def _no(reason: str, **extra: Any) -> Dict[str, Any]:
    return dict({"ok": False, "reason": reason}, **extra)


def _check_schema(p: Mapping[str, Any]) -> Optional[Dict[str, Any]]:
    """Strict schema. Missing OR unknown fields both refuse."""
    missing = [k for k in REQUIRED_PAYLOAD_FIELDS if k not in p]
    if missing:
        return _no("MANDATE_FIELD_MISSING", detail={"missing": sorted(missing)})
    unknown = [k for k in p if k not in REQUIRED_PAYLOAD_FIELDS]
    if unknown:
        return _no("MANDATE_UNKNOWN_FIELD", detail={"unknown": sorted(unknown)})
    for blk, req in (("capital", REQUIRED_CAPITAL_FIELDS),
                     ("loss_limits", REQUIRED_LOSS_FIELDS),
                     ("promotion", REQUIRED_PROMOTION_FIELDS)):
        sub = p.get(blk)
        if not isinstance(sub, dict):
            return _no("MANDATE_BLOCK_NOT_OBJECT", detail={"block": blk})
        m = [k for k in req if k not in sub]
        u = [k for k in sub if k not in req]
        if m or u:
            return _no("MANDATE_BLOCK_SCHEMA",
                       detail={"block": blk, "missing": sorted(m),
                               "unknown": sorted(u)})
    return None


def _check_binding(p: Mapping[str, Any], *, environment: str,
                   service_role: str, series: str) -> Optional[Dict[str, Any]]:
    """Requirement 2: the mandate must name THIS deployment exactly."""
    for field, expected in (("venue", EXPECTED_VENUE),
                            ("strategy", EXPECTED_STRATEGY),
                            ("execution_mode", EXPECTED_EXECUTION_MODE),
                            ("environment", environment),
                            ("service_role", service_role),
                            ("series", series)):
        got = p.get(field)
        if not isinstance(got, str) or got != expected:
            return _no("MANDATE_BINDING_MISMATCH",
                       detail={"field": field, "expected": expected,
                               "got": (got if isinstance(got, str)
                                       else type(got).__name__)[:40]})
    if p.get("kind") not in ("standing", "campaign"):
        return _no("MANDATE_KIND_UNKNOWN", detail={"kind": str(p.get("kind"))[:20]})
    acts = p.get("allowed_actions")
    if not isinstance(acts, list) or not acts:
        return _no("MANDATE_ACTIONS_EMPTY")
    bad = [a for a in acts if not isinstance(a, str) or a not in KNOWN_ACTIONS]
    if bad:
        return _no("MANDATE_ACTION_UNKNOWN",
                   detail={"unknown": [str(b)[:20] for b in bad[:4]]})
    if len(set(acts)) != len(acts):
        return _no("MANDATE_ACTIONS_DUPLICATED")
    return None


def _check_numbers(p: Mapping[str, Any]) -> Optional[Dict[str, Any]]:
    if _pos_int(p.get("seq")) is None:
        return _no("MANDATE_SEQ_INVALID")
    for f in ("max_windows_per_day", "max_submissions_per_day",
              "residual_cap_contracts"):
        if _pos_int(p.get(f)) is None:
            return _no("MANDATE_RATE_INVALID", detail={"field": f})
    for blk, fields in (("capital", REQUIRED_CAPITAL_FIELDS),
                        ("loss_limits", REQUIRED_LOSS_FIELDS)):
        for f in fields:
            if _money(dict(p[blk]).get(f)) is None:
                return _no("MANDATE_MONEY_INVALID",
                           detail={"block": blk, "field": f,
                                   "note": "must be a non-negative decimal "
                                           "STRING; floats are refused"})
    pr = dict(p["promotion"])
    if _pos_int(pr.get("min_settled_windows")) is None:
        return _no("MANDATE_PROMOTION_SAMPLE_INVALID")
    if _money(pr.get("min_expectancy_usd")) is None:
        return _no("MANDATE_PROMOTION_EXPECTANCY_INVALID")
    if not isinstance(pr.get("oos_evidence_id"), str) \
            or not str(pr.get("oos_evidence_id")).strip():
        return _no("MANDATE_PROMOTION_OOS_EVIDENCE_MISSING")
    # REQUIREMENT 7, ENFORCED IN THE SCHEMA. A mandate cannot opt out of
    # bounded live validation, so shadow expectancy alone can never promote.
    if pr.get("requires_bounded_live_validation") is not True:
        return _no("MANDATE_PROMOTION_MUST_REQUIRE_LIVE_VALIDATION",
                   detail={"note": "shadow expectancy may only WITHHOLD "
                                   "live arming, never enable it"})
    return None


def _check_validity(p: Mapping[str, Any], now: dt.datetime
                    ) -> Optional[Dict[str, Any]]:
    nb, na = _ts(p.get("not_before")), _ts(p.get("not_after"))
    if nb is None:
        return _no("MANDATE_NOT_BEFORE_INVALID",
                   detail={"note": "ISO-8601 with an explicit offset"})
    if na is None:
        return _no("MANDATE_NOT_AFTER_INVALID",
                   detail={"note": "ISO-8601 with an explicit offset"})
    if (na - nb).total_seconds() <= 0:
        return _no("MANDATE_WINDOW_INVERTED")
    if (na - nb).total_seconds() > MAX_MANDATE_S:
        return _no("MANDATE_DURATION_ABOVE_CEILING",
                   detail={"requested_s": (na - nb).total_seconds(),
                           "ceiling_s": MAX_MANDATE_S})
    if now < nb:
        return _no("MANDATE_NOT_YET_VALID",
                   detail={"not_before": nb.isoformat()})
    if now >= na:
        return _no("MANDATE_EXPIRED", detail={"not_after": na.isoformat()})
    return None


def verify(raw: Any, *, environment: str, service_role: str, series: str,
           now: Optional[dt.datetime] = None,
           seq_store: Optional[SeqStore] = None,
           revoked: Any = None,
           record_seq: bool = False) -> Dict[str, Any]:
    """The one verdict. Default NO.

    `revoked` is the revocation set the watchdog serves. **None means NOT
    ESTABLISHED and refuses** -- an executor that cannot find out whether its
    mandate was revoked is not authorized, the same rule `HaltGate` applies
    to the latch. Pass an explicit empty collection to mean "nothing revoked".

    `record_seq` is False by default so that REPORTING cannot consume the
    monotonic mark. Only an enforcing caller records.
    """
    now = now or _utc()
    if not MANDATE_PUBKEYS:
        return _no("MANDATE_NO_TRUSTED_KEY",
                   detail={"note": "MANDATE_PUBKEYS is empty; the shipped "
                                   "state refuses every mandate"})
    if raw is None or (isinstance(raw, str) and not raw.strip()):
        return _no("MANDATE_ABSENT")
    try:
        doc = json.loads(raw) if isinstance(raw, (str, bytes)) else raw
    except BaseException:                                      # noqa: BLE001
        return _no("MANDATE_NOT_JSON")
    if not isinstance(doc, dict):
        return _no("MANDATE_NOT_OBJECT")
    payload, sig, key_id = doc.get("payload"), doc.get("sig"), doc.get("key_id")
    if not isinstance(payload, dict):
        return _no("MANDATE_PAYLOAD_MISSING")
    if not isinstance(sig, str) or not isinstance(key_id, str):
        return _no("MANDATE_SIGNATURE_FIELDS_MISSING")
    pub = MANDATE_PUBKEYS.get(key_id)
    if not pub:
        return _no("MANDATE_KEY_UNKNOWN", detail={"key_id": key_id[:40]})
    if payload.get("schema") != SCHEMA:
        return _no("MANDATE_SCHEMA_UNKNOWN",
                   detail={"schema": str(payload.get("schema"))[:40]})

    # LAZILY, ONE AT A TIME. Building these as a tuple evaluated all four
    # eagerly, so `_check_numbers` indexed a block that `_check_schema` had
    # just rejected and raised KeyError instead of returning a named
    # refusal. A verifier that can raise is a verifier whose answer depends
    # on the caller's exception handling, which is not fail-closed.
    for check in (lambda: _check_schema(payload),
                  lambda: _check_binding(payload, environment=environment,
                                         service_role=service_role,
                                         series=series),
                  lambda: _check_numbers(payload),
                  lambda: _check_validity(payload, now)):
        out = check()
        if out is not None:
            return out

    # THE SIGNATURE IS CHECKED AFTER THE SHAPE and that order is deliberate:
    # a malformed document gets a reason the owner can act on instead of a
    # bare "bad signature". It is checked BEFORE anything is recorded or
    # trusted, so an unsigned document never advances the monotonic mark.
    if not _verify_ed25519(pub, sig, canonical_bytes(payload)):
        return _no("MANDATE_SIGNATURE_INVALID", detail={"key_id": key_id[:40]})

    if revoked is None:
        return _no("MANDATE_REVOCATION_UNKNOWN",
                   detail={"note": "revocation state could not be "
                                   "established; refusing"})
    mid, seq = str(payload["mandate_id"]), int(payload["seq"])
    try:
        rev = set(str(x) for x in revoked)
    except TypeError:
        return _no("MANDATE_REVOCATION_UNREADABLE")
    if mid in rev or ("%s#%d" % (mid, seq)) in rev:
        return _no("MANDATE_REVOKED", detail={"mandate_id": mid[:60]})

    store = seq_store or SeqStore()
    try:
        high = store.highest(key_id)
    except MandateUnavailable as exc:
        return _no("MANDATE_SEQ_STORE_UNAVAILABLE",
                   detail={"error": str(exc)[:120]})
    except BaseException as exc:                               # noqa: BLE001
        if isinstance(exc, (KeyboardInterrupt, SystemExit)):
            raise
        return _no("MANDATE_SEQ_STORE_UNAVAILABLE",
                   detail={"error": type(exc).__name__})
    if seq <= high:
        return _no("MANDATE_REPLAYED_OR_ROLLED_BACK",
                   detail={"seq": seq, "highest_accepted": high})
    if record_seq:
        try:
            store.record(key_id, seq)
        except BaseException as exc:                           # noqa: BLE001
            if isinstance(exc, (KeyboardInterrupt, SystemExit)):
                raise
            return _no("MANDATE_SEQ_RECORD_FAILED",
                       detail={"error": type(exc).__name__})

    return {"ok": True, "reason": None, "key_id": key_id,
            "mandate_id": mid, "seq": seq, "kind": payload["kind"],
            "scope": dict(payload),
            "labels": ("VERIFIED ONLY. This authorizes nothing by itself: "
                       "the arming boundary still applies the intersection "
                       "of this scope with the running limits, the halt "
                       "latch, the promotion preconditions and the bounded "
                       "live validation requirement.")}


def telemetry(verdict: Mapping[str, Any]) -> Dict[str, Any]:
    """Safe to log. Names the verdict and the identity, never the document.

    The signature, the payload and the key bytes are deliberately absent: a
    mandate is not a credential, but publishing one in logs invites someone
    to replay it against a rolled-back seq store.
    """
    return {
        "ok": bool(verdict.get("ok")),
        "reason": verdict.get("reason"),
        "key_id": verdict.get("key_id"),
        "mandate_id": verdict.get("mandate_id"),
        "seq": verdict.get("seq"),
        "kind": verdict.get("kind"),
        "trusted_keys": sorted(MANDATE_PUBKEYS),
        "schema": SCHEMA,
        "max_mandate_s": MAX_MANDATE_S,
        "enforcing": False,
        "labels": ("PHASE 1: REPORTING ONLY. No arming decision consults "
                   "this module yet."),
    }
