"""The owner's SIGNATURE, enforced inside `authorize_arming`.

WHY THIS GATE EXISTS, in one paragraph, because the reason is the whole
design. `l5_campaign_approval` reads the owner's approval from a Railway
variable and its docstring claims "Claude cannot write it, so Claude cannot
approve a campaign". `l5_mandate_signature` records that this is false in
practice: anyone holding a Railway token can set the variable, and three were
set that way in session 012Mo8AP. A signature does not try to control custody
of the bytes -- it makes writing them INSUFFICIENT. The payload must carry an
Ed25519 signature from a key whose private half the owner holds offline and
which this process has never seen.

ON THE KEYPAIR IN THIS FILE. It is generated inside the test process, used
only here, and is NOT and must never be the owner's production signing key --
that one is generated by the owner, offline, per `docs/OWNER_MANDATE_SIGNING.md`
and never enters this repository, Railway, a log or a chat. A throwaway key is
the only way to prove the mechanism actually rejects what it should.

WHAT MUST HOLD: with no trusted key the gate is INERT and every existing
authorization path is unchanged; the moment a trusted key is registered a
valid owner-signed mandate is REQUIRED; and nothing obtainable by writing the
variable can satisfy it.
"""
from __future__ import annotations

import datetime as dt
import json
import os

import pytest
from cryptography.hazmat.primitives import serialization as _S
from cryptography.hazmat.primitives.asymmetric import ed25519

from src import l5_live_authorization as AUTH
from src import l5_mandate_signature as MS

SERIES = "cpc-btc-updown-15m-"
ENVIRONMENT = "production"
ROLE = "l5-pmus-live"
KEY_ID = "test-key-not-the-owners"


def _keypair():
    priv = ed25519.Ed25519PrivateKey.generate()
    pub = priv.public_key().public_bytes(
        encoding=_S.Encoding.Raw, format=_S.PublicFormat.Raw).hex()
    return priv, pub


def _payload(*, seq=1, exposure="5", daily="5", mode="MAKER_ONLY"):
    now = dt.datetime.now(dt.timezone.utc)
    return {
        "schema": MS.SCHEMA, "kind": "standing",
        "mandate_id": "test-001", "seq": seq,
        "venue": "PMUS", "strategy": "l5-two-sided-btc15m",
        "environment": ENVIRONMENT, "service_role": ROLE, "series": SERIES,
        "not_before": (now - dt.timedelta(hours=1)).isoformat(),
        "not_after": (now + dt.timedelta(hours=3)).isoformat(),
        "allowed_actions": ["OPEN", "COMPLETE", "CANCEL"],
        "execution_mode": mode,
        "max_windows_per_day": 8, "max_submissions_per_day": 56,
        "capital": {"max_cash_deployed_usd": "5",
                    "max_total_exposure_usd": exposure,
                    "campaign_budget_usd": "5"},
        "loss_limits": {"daily_realized_loss_halt_usd": daily,
                        "max_cumulative_loss_usd": "20"},
        "residual_cap_contracts": 3,
        "promotion": {"min_settled_windows": 300,
                      "min_expectancy_usd": "0.05",
                      "oos_evidence_id": "btc15m-oos-20261023",
                      "requires_bounded_live_validation": True},
    }


def _sign(priv, payload, key_id=KEY_ID):
    sig = priv.sign(MS.canonical_bytes(payload)).hex()
    return json.dumps({"payload": payload, "sig": sig, "key_id": key_id})


class _Limits:
    """Only what the gate reads off it."""

    def __init__(self, exposure="5", daily="5"):
        self.max_total_exposure_usd = AUTH.D(exposure)
        self.daily_realized_loss_halt_usd = AUTH.D(daily)


class _FakeStores:
    """The watchdog's two documents, served in-process.

    The real path is `HttpSeqFloorStore` / `HttpRevocationStore` over
    private networking. These tests must not open sockets, so the two
    classes are substituted -- but EVERY test that cares about absence,
    staleness or malformation drives the refusal through the gate rather
    than around it.
    """

    def __init__(self, floor=0, revoked=(), raises=None):
        self._floor, self._revoked, self._raises = floor, revoked, raises

    def floor_store(self, url, **kw):
        outer = self

        class _S:
            def floor(self, key_id, **_kw):
                if outer._raises == "floor":
                    raise MS.MandateUnavailable("floor document absent")
                return outer._floor
        return _S()

    def revocation_store(self, url, **kw):
        outer = self

        class _S:
            def revoked(self, **_kw):
                if outer._raises == "revoked":
                    raise MS.MandateUnavailable("revocation document absent")
                return frozenset(outer._revoked)
        return _S()


@pytest.fixture
def armed_env(monkeypatch, tmp_path):
    """A trusted key registered, the halt latch present, the watchdog
    publishing both documents, limits at $5."""
    priv, pub = _keypair()
    monkeypatch.setitem(MS.MANDATE_PUBKEYS, KEY_ID, pub)
    monkeypatch.setenv("RAILWAY_ENVIRONMENT_NAME", ENVIRONMENT)
    monkeypatch.setenv(AUTH.SERVICE_ROLE_ENV, ROLE)
    monkeypatch.setenv(AUTH.SERIES_ENV, SERIES)
    monkeypatch.setenv("L5_LIVE_ROOT", str(tmp_path))
    monkeypatch.setenv(MS.STORE_URL_ENV, "http://watchdog.internal:8080")
    st = _FakeStores()
    monkeypatch.setattr(MS, "HttpSeqFloorStore", st.floor_store)
    monkeypatch.setattr(MS, "HttpRevocationStore", st.revocation_store)
    return priv


def _serve(monkeypatch, **kw):
    st = _FakeStores(**kw)
    monkeypatch.setattr(MS, "HttpSeqFloorStore", st.floor_store)
    monkeypatch.setattr(MS, "HttpRevocationStore", st.revocation_store)


def _arm(**kw):
    """Call the real gate. It will refuse for SOME reason; these tests assert
    on WHICH reason, and specifically that the signature step is reached and
    decides before the later steps do."""
    base = dict(market="cpc-btc-updown-15m-2026-10-24-2200z",
                preflight=None, store=None, halted=False, reconciled=True,
                halt_gate_present=True, unresolved=(),
                limits=_Limits(), shadow_locked=False,
                series=SERIES, max_windows=8,
                campaign=None, path=None, require_durable=False)
    base.update(kw)
    with pytest.raises(AUTH.ArmingRefusal) as e:
        AUTH.authorize_arming(**base)
    return e.value


def _reason(exc):
    return str(getattr(exc, "reason", None) or getattr(exc, "args", [""])[0])


# ---------------------------------------------------------------- inert
def test_with_no_trusted_key_the_gate_is_inert():
    """THE SHIPPED STATE. An empty registry must leave every existing
    authorization path exactly as it was -- the 567 authorization tests that
    pass today are the evidence, and this pins the precondition they rely
    on."""
    assert MS.MANDATE_PUBKEYS == {}, (
        "a key committed into the repo would silently make the gate "
        "mandatory for every existing test and every one-window probe")


# -------------------------------------------------- the gate actually binds
def test_a_registered_key_makes_a_signature_REQUIRED(armed_env, monkeypatch):
    monkeypatch.delenv(MS.MANDATE_ENV, raising=False)
    assert _reason(_arm()) == "MANDATE_ABSENT"


def test_writing_the_variable_without_the_key_cannot_satisfy_it(
        armed_env, monkeypatch):
    """THE WHOLE POINT. An agent or attacker holding a Railway token can set
    this variable to anything. None of it verifies."""
    for forged in (
            json.dumps({"payload": _payload(), "sig": "00" * 64,
                        "key_id": KEY_ID}),            # invalid signature
            json.dumps({"payload": _payload()}),       # no signature at all
            json.dumps({"approved": True}),            # the campaign shape
            "true", "{}", "not json at all"):
        monkeypatch.setenv(MS.MANDATE_ENV, forged)
        assert _reason(_arm()).startswith("MANDATE_"), forged[:40]


def test_a_signature_from_another_key_is_refused(armed_env, monkeypatch):
    other, _pub = _keypair()
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(other, _payload()))
    assert _reason(_arm()) in ("MANDATE_SIGNATURE_INVALID",
                               "MANDATE_KEY_UNKNOWN")


def test_tampering_with_the_payload_breaks_the_signature(armed_env,
                                                         monkeypatch):
    """The signature covers a canonical serialization of the WHOLE payload,
    so raising the capital after signing invalidates it."""
    p = _payload(exposure="5")
    doc = json.loads(_sign(armed_env, p))
    doc["payload"]["capital"]["max_total_exposure_usd"] = "500"
    monkeypatch.setenv(MS.MANDATE_ENV, json.dumps(doc))
    assert _reason(_arm()) == "MANDATE_SIGNATURE_INVALID"


def test_an_unknown_key_id_is_refused(armed_env, monkeypatch):
    monkeypatch.setenv(MS.MANDATE_ENV,
                       _sign(armed_env, _payload(), key_id="someone-else"))
    assert _reason(_arm()) == "MANDATE_KEY_UNKNOWN"


# ------------------------------------------------- scope cannot be widened
def test_running_limits_wider_than_signed_are_refused(armed_env,
                                                      monkeypatch):
    """A limit widened AFTER signing invalidates the signed scope rather
    than inheriting it -- the same intersection discipline the campaign
    approval uses."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload(
        exposure="5", daily="5")))
    exc = _arm(limits=_Limits(exposure="20", daily="5"))
    assert _reason(exc) == "MANDATE_LIMITS_WIDER_THAN_SIGNED"
    exc = _arm(limits=_Limits(exposure="5", daily="50"))
    assert _reason(exc) == "MANDATE_LIMITS_WIDER_THAN_SIGNED"


def test_unreadable_running_limits_refuse_rather_than_pass(armed_env,
                                                           monkeypatch):
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    assert _reason(_arm(limits=None)) == "MANDATE_RUNNING_LIMITS_UNREADABLE"


def test_a_non_maker_mode_is_refused_even_when_signed(armed_env,
                                                      monkeypatch):
    """No signed mandate may authorize a crossing order."""
    monkeypatch.setenv(MS.MANDATE_ENV,
                       _sign(armed_env, _payload(mode="TAKER")))
    # the schema itself may reject it; either way it must not be authorized
    assert _reason(_arm()).startswith("MANDATE_")


# ----------------------------------------------------- revocation must exist
def test_without_the_halt_latch_a_signed_mandate_is_refused(armed_env,
                                                            monkeypatch):
    """A mandate that cannot be WITHDRAWN is not accepted. The watchdog does
    not serve a revocation list yet, so the halt latch is the established
    revocation route -- and with no latch there is no route at all."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    assert _reason(_arm(halt_gate_present=False)) \
        == "MANDATE_REVOCATION_UNAVAILABLE"


# ------------------------------------------- a valid mandate gets PAST 2c
def test_a_valid_signed_mandate_passes_the_signature_step(armed_env,
                                                          monkeypatch):
    """It must not then be authorized by THIS step alone: every later
    refusal still applies. What this asserts is that the signature step
    stopped being the reason."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    reason = _reason(_arm())
    assert not reason.startswith("MANDATE_"), reason
    # AND IT IS NOT AUTHORIZED BY THE SIGNATURE ALONE, which is the design:
    # the signature is a NECESSARY ADDITIONAL condition, so the campaign
    # document or the legacy handshake is still required after it.
    assert reason == "OWNER_AUTHORIZATION_ABSENT"


def test_the_signature_step_runs_BEFORE_the_halt_and_preflight_steps(
        armed_env, monkeypatch):
    """Ordering matters for the operator's logs: an unsigned mandate must be
    named as such rather than reported as some incidental inner failure."""
    monkeypatch.delenv(MS.MANDATE_ENV, raising=False)
    assert _reason(_arm(halted=True)) == "MANDATE_ABSENT"
    assert _reason(_arm(reconciled=False)) == "MANDATE_ABSENT"


# ------------------------------------- the watchdog documents are REQUIRED
def test_an_unconfigured_store_refuses(armed_env, monkeypatch):
    """A mandate whose currency cannot be established is not authorized."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    monkeypatch.delenv(MS.STORE_URL_ENV, raising=False)
    assert _reason(_arm()) == "MANDATE_STORE_UNCONFIGURED"


def test_an_absent_replay_floor_refuses(armed_env, monkeypatch):
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    _serve(monkeypatch, raises="floor")
    assert _reason(_arm()) == "MANDATE_SEQ_FLOOR_UNAVAILABLE"


def test_an_absent_revocation_list_refuses(armed_env, monkeypatch):
    """Absence is NOT 'nothing revoked'."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    _serve(monkeypatch, raises="revoked")
    assert _reason(_arm()) == "MANDATE_REVOCATION_UNAVAILABLE"


def test_a_revoked_mandate_is_refused(armed_env, monkeypatch):
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload()))
    _serve(monkeypatch, revoked=("test-001",))
    assert _reason(_arm()).startswith("MANDATE_")


def test_a_replayed_mandate_is_refused_by_the_floor(armed_env, monkeypatch):
    """seq strictly increases, so raising the floor past a mandate's seq is
    what stops a rollback to an older, looser document."""
    monkeypatch.setenv(MS.MANDATE_ENV, _sign(armed_env, _payload(seq=1)))
    _serve(monkeypatch, floor=5)
    assert _reason(_arm()).startswith("MANDATE_")


def test_the_floor_is_read_from_the_watchdog_not_our_own_disk():
    """A floor this process can WRITE is a floor it can roll back, which
    would let an older owner-signed mandate be replayed. The gate must use
    the HTTP clients, never the local SeqStore-shaped writer."""
    import inspect
    src = inspect.getsource(AUTH.authorize_arming)
    assert "HttpSeqFloorStore" in src
    assert "HttpRevocationStore" in src
    assert "WatchdogSeqWriter" not in src
